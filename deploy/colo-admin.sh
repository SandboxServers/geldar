#!/bin/sh
# Runs one administration subcommand in the one-shot admin container (decision 0133). The container starts with
# `run --rm` under the profile admin. Nothing is brought up, stopped or removed, and no volume is touched. Every
# compose call names the geldar-colo project. Only token-mint mounts a host directory: GELDAR_TOKENS_DIR, outside the
# repo and mode 0700, bound at /run/tokens by an overlay written to the state directory and removed when the run ends.
# The token value is never printed: the script prints the path and the byte length of the file, and nothing else.
# Set DEPLOY_DRY_RUN=1 to print the plan; it runs only the read-only checks and `config --quiet`.
set -eu
. "$(dirname "$0")/common.sh"

ADMIN_OVERLAY=
# Replaces the EXIT trap of common.sh: the generated overlay goes with the work directory.
trap 'rm -f "$ADMIN_OVERLAY"; rm -rf "$WORK"' EXIT

# Runs one compose call for the admin service. The token overlay is added only for token-mint.
adm() {
  if [ -n "$ADMIN_OVERLAY" ] && [ -n "$EXTRA_OVERLAY" ]; then
    docker compose -p "$PROJECT" -f "$COMPOSE_FILE" -f "$NATS_OVERLAY" -f "$SECRETS_OVERLAY" -f "$EXTRA_OVERLAY" -f "$ADMIN_OVERLAY" --profile admin "$@"
  elif [ -n "$ADMIN_OVERLAY" ]; then
    docker compose -p "$PROJECT" -f "$COMPOSE_FILE" -f "$NATS_OVERLAY" -f "$SECRETS_OVERLAY" -f "$ADMIN_OVERLAY" --profile admin "$@"
  elif [ -n "$EXTRA_OVERLAY" ]; then
    docker compose -p "$PROJECT" -f "$COMPOSE_FILE" -f "$NATS_OVERLAY" -f "$SECRETS_OVERLAY" -f "$EXTRA_OVERLAY" --profile admin "$@"
  else
    docker compose -p "$PROJECT" -f "$COMPOSE_FILE" -f "$NATS_OVERLAY" -f "$SECRETS_OVERLAY" --profile admin "$@"
  fi
}

# Checks the token-mint arguments: <player> [--out /run/tokens/<name>.token]. Sets player, out and TOKEN_REL.
mint_args() {
  [ $# -ge 1 ] || die "token-mint needs a player id"
  player=$1
  shift
  printf '%s' "$player" | grep -Eq '^[A-Za-z0-9_-]+$' || die "player id must use only A-Z a-z 0-9 _ -"
  out=/run/tokens/$player.token
  if [ $# -gt 0 ]; then
    [ $# -eq 2 ] && [ "$1" = --out ] || die "token-mint takes <player> [--out /run/tokens/<name>.token]"
    out=$2
  fi
  case $out in
    /run/tokens/*) ;;
    *) die "--out must be under /run/tokens (the mounted tokens directory): $out" ;;
  esac
  case $out in *..*) die "--out must not contain '..'" ;; esac
  TOKEN_REL=${out#/run/tokens/}
  printf '%s' "$TOKEN_REL" | grep -Eq '^[A-Za-z0-9_-]+\.token$' || die "--out must name one file <name>.token in /run/tokens"
}

# GELDAR_TOKENS_DIR must be set, be a directory, sit outside the repo checkout, and be mode 0700. Sets TOKENS_REAL.
tokens_checks() {
  [ -n "${GELDAR_TOKENS_DIR:-}" ] || die "token-mint needs GELDAR_TOKENS_DIR: a host directory outside the repo, mode 0700"
  [ -d "$GELDAR_TOKENS_DIR" ] || die "GELDAR_TOKENS_DIR is not a directory: $GELDAR_TOKENS_DIR"
  TOKENS_REAL=$(cd "$GELDAR_TOKENS_DIR" && pwd -P) || die "cannot resolve GELDAR_TOKENS_DIR"
  ROOT_REAL=$(cd "$ROOT" && pwd -P) || die "cannot resolve the repo checkout"
  case $TOKENS_REAL in
    "$ROOT_REAL" | "$ROOT_REAL"/*) die "GELDAR_TOKENS_DIR is inside the repo checkout; use a directory outside it" ;;
  esac
  printf '%s' "$TOKENS_REAL" | grep -Eq '^[A-Za-z0-9/._:-]+$' ||
    die "GELDAR_TOKENS_DIR has characters the overlay cannot quote (use A-Z a-z 0-9 / . _ : -)"
  m=$(stat -c %a "$TOKENS_REAL") || die "cannot stat GELDAR_TOKENS_DIR"
  [ "$m" = 700 ] || die "GELDAR_TOKENS_DIR has mode $m; it must be 0700"
}

# Writes the overlay that mounts the tokens directory into the admin service only. It is written with mode 0600.
write_overlay() {
  ADMIN_OVERLAY=$STATE_DIR/admin-tokens.override.yml
  (
    umask 077
    mkdir -p "$STATE_DIR" &&
      printf '%s\n' "# Generated by deploy/colo-admin.sh for one token-mint run; removed when the run ends." \
        "services:" "  admin:" "    volumes:" "      - type: bind" "        source: \"$TOKENS_REAL\"" \
        "        target: /run/tokens" >"$ADMIN_OVERLAY"
  ) || die "cannot write the admin overlay in $STATE_DIR"
  [ "$(stat -c %a "$ADMIN_OVERLAY")" = 600 ] || die "the admin overlay is not mode 0600; refusing"
}

# Checks the minted file by its metadata only: it exists, is not empty, and is mode 0600. Its value is never read out.
verify_token() {
  f=$TOKENS_REAL/$TOKEN_REL
  [ -f "$f" ] && [ -s "$f" ] || die "the token file was not written: $TOKEN_REL"
  m=$(stat -c %a "$f") || die "cannot stat the token file"
  [ "$m" = 600 ] || die "the token file has mode $m; it must be 0600 (the value is not shown)"
  n=$(wc -c <"$f" | tr -d ' ')
  say "token file written: $f ($n bytes); the value is not printed"
}

cmd=${1:-}
case $cmd in
  migrate | owner-add | player-add | token-mint | token-revoke | players-status | ensure-skins-bucket) shift ;;
  *) die "unknown subcommand '$cmd'; use migrate, owner-add, player-add, token-mint, token-revoke, players-status or ensure-skins-bucket" ;;
esac
if [ "$cmd" = token-mint ]; then
  mint_args "$@"
fi

plan_header
[ -n "$PROJECT" ] || die "no compose project name; refusing"
say "admin subcommand: $cmd (one-shot container, profile admin, decision 0133)"
need docker
check_prereqs
load_release "$RELEASE_FILE"
[ -n "${GELDAR_ADMIN_IMAGE:-}" ] || die "the release manifest has no GELDAR_ADMIN_IMAGE; pin the admin image by digest"
if [ "$cmd" = token-mint ]; then
  tokens_checks
fi
check_merged_config
check_secrets

if [ "$DRY_RUN" = 1 ]; then
  say "dry-run, not run: docker compose -p $PROJECT ... --profile admin run --rm admin $cmd $*"
  if [ "$cmd" = token-mint ]; then
    say "dry-run, not run: write $STATE_DIR/admin-tokens.override.yml (mount $TOKENS_REAL at /run/tokens)"
  fi
  adm config --quiet || die "admin service config does not validate"
  exit 0
fi

if [ "$cmd" = token-mint ]; then
  write_overlay
  adm config --quiet || die "admin service config does not validate"
  adm run --rm admin token-mint "$player" --out "$out" || die "token-mint failed"
  verify_token
else
  adm config --quiet || die "admin service config does not validate"
  adm run --rm admin "$cmd" "$@" || die "admin $cmd failed"
  say "admin $cmd: done (the admin container was removed; no volume was touched)"
fi
