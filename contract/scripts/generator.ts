/**
 * Builds the committed files under src/generated/ from schemas/. The output is a
 * pure function of the schema files (sorted by name, no timestamps), so the same
 * input gives the same bytes on Windows and Linux and `findStale` can compare.
 * Cross-file $refs resolve from schemas/ only: every schema is added to Ajv first,
 * and json-schema-to-typescript runs with cwd set to that folder.
 */
import { readdir, readFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ajv2020Module from 'ajv/dist/2020.js';
import ajvStandaloneModule from 'ajv/dist/standalone/index.js';
import ajvFormatsModule from 'ajv-formats';
import { compile } from 'json-schema-to-typescript';

// ajv and ajv-formats ship CommonJS with `exports.default` set. A default import gives module.exports,
// which holds the same `default` for both runtime and typings, so read it from there.
const Ajv2020 = ajv2020Module.default;
const addFormats = ajvFormatsModule.default;
const standaloneCode = ajvStandaloneModule.default;

// Ajv 8 writes runtime helpers as require() calls even in ESM mode (for minLength/maxLength it
// needs ajv/dist/runtime/ucs2length). Giving the ESM output its own require keeps it loadable.
const esmRequirePrelude =
  'import { createRequire } from "node:module";\nconst require = createRequire(import.meta.url);\n';

const contractDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemasDir = join(contractDir, 'schemas');
const banner = '// Generated by contract/scripts/generate.ts. Do not edit.\n';

interface LoadedSchema {
  /** File stem, for example `snapshot` for schemas/snapshot.schema.json. */
  name: string;
  schema: Record<string, unknown> & { $id: string; title?: string };
}

async function loadSchemas(): Promise<LoadedSchema[]> {
  const files = (await readdir(schemasDir)).filter((file) => file.endsWith('.schema.json')).sort();
  return Promise.all(
    files.map(async (file) => ({
      name: file.slice(0, -'.schema.json'.length),
      schema: JSON.parse(await readFile(join(schemasDir, file), 'utf8')),
    })),
  );
}

/**
 * A $defs entry that fixes its `type` property to a constant, such as HelloFrame with "hello":
 * one member of a union that is told apart by `type`.
 */
function isUnionMember(definition: Record<string, unknown>): boolean {
  const properties = definition.properties as Record<string, Record<string, unknown>> | undefined;
  return properties?.type?.const !== undefined;
}

/**
 * The validators to export, keyed by export name. Each schema with a title gets one named after
 * the title, and each union member in its $defs gets one named after the definition, pointing at
 * that definition by fragment so Ajv compiles it within the schema.
 */
function validatorExports(schemas: LoadedSchema[]): Map<string, string> {
  const exported = new Map<string, string>();
  for (const { schema } of schemas) {
    if (schema.title === undefined) continue;
    exported.set(`validate${schema.title}`, schema.$id);
    const defs = (schema.$defs ?? {}) as Record<string, Record<string, unknown>>;
    for (const [name, definition] of Object.entries(defs)) {
      if (!isUnionMember(definition)) continue;
      const exportName = `validate${name}`;
      if (exported.has(exportName)) throw new Error(`duplicate validator export ${exportName}`);
      exported.set(exportName, `${schema.$id}#/$defs/${name}`);
    }
  }
  return exported;
}

/** Ajv's standalone validators, as ESM. Schemas are added before compiling so $refs stay local. */
async function buildValidators(schemas: LoadedSchema[]): Promise<string> {
  const ajv = new Ajv2020({ strict: true, allErrors: true, code: { source: true, esm: true } });
  addFormats(ajv);
  for (const { schema } of schemas) ajv.addSchema(schema);

  const exported = Object.fromEntries(validatorExports(schemas));
  return banner + esmRequirePrelude + standaloneCode(ajv, exported);
}

/** Declarations for validators.js, one per export of validatorExports. */
function buildValidatorDeclarations(schemas: LoadedSchema[]): string {
  const lines = [...validatorExports(schemas).keys()].map(
    (name) => `export declare const ${name}: ValidateFunction;`,
  );
  return `${banner}import type { ValidateFunction } from 'ajv';\n\n${lines.join('\n')}\n`;
}

/**
 * One exported type per titled schema, plus each definition of an untitled schema
 * (common.schema.json). json-schema-to-typescript also emits the definitions a schema
 * references from other files, so declarations are de-duplicated by name; the text of
 * a declaration is identical wherever it appears.
 */
async function buildTypes(schemas: LoadedSchema[]): Promise<string> {
  const declarations = new Map<string, string>();
  for (const { schema } of schemas) {
    const defNames = new Set(Object.keys(schema.$defs ?? {}));
    const text = await compile(schema as Parameters<typeof compile>[0], schema.title ?? 'Unnamed', {
      cwd: schemasDir,
      bannerComment: '',
      unreachableDefinitions: schema.title === undefined,
    });
    // Each declaration starts at column 0 (after its JSDoc, if any); nested members are indented.
    for (const part of text.split(/\n(?=(?:\/\*\*[\s\S]*?\*\/\n)?export )/)) {
      const match = /export (?:interface|type) (\w+)/.exec(part);
      const name = match?.[1];
      if (name === undefined || declarations.has(name)) continue;
      if (schema.title === undefined && !defNames.has(name)) continue;
      declarations.set(name, part.trim());
    }
  }
  return `${banner}\n${[...declarations.values()].join('\n\n')}\n`;
}

/** Every generated file, keyed by its path relative to contract/. */
export async function generate(): Promise<Map<string, string>> {
  const schemas = await loadSchemas();
  return new Map([
    ['src/generated/types.ts', await buildTypes(schemas)],
    ['src/generated/validators.js', await buildValidators(schemas)],
    ['src/generated/validators.d.ts', buildValidatorDeclarations(schemas)],
  ]);
}

/** Paths of generated files that are missing or differ from what the schemas produce. */
export async function findStale(): Promise<string[]> {
  const stale: string[] = [];
  for (const [path, text] of await generate()) {
    const current = await readFile(join(contractDir, path), 'utf8').catch(() => undefined);
    if (current !== text) stale.push(path);
  }
  return stale;
}
