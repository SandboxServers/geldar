/**
 * Builds the committed files under src/generated/ from schemas/. The output is a
 * pure function of the schema files (sorted by name, no timestamps), so the same
 * input gives the same bytes on Windows and Linux and `findStale` can compare.
 * Cross-file $refs resolve from schemas/ only: every schema is added to Ajv first,
 * and json-schema-to-typescript runs with cwd set to that folder.
 */
import { readdir, readFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ajv2020Module from 'ajv/dist/2020.js';
import ajvStandaloneModule from 'ajv/dist/standalone/index.js';
import ajvFormatsModule from 'ajv-formats';
import { compile } from 'json-schema-to-typescript';

// ajv and ajv-formats ship CommonJS with `exports.default` set. A default import gives module.exports,
// which holds the same `default` for both runtime and typings, so read it from there.
const Ajv2020 = ajv2020Module.default;
const addFormats = ajvFormatsModule.default;
const standaloneCode = ajvStandaloneModule.default;

// Ajv 8 writes runtime helpers as require() calls even in ESM mode (for minLength/maxLength it
// needs ajv/dist/runtime/ucs2length). Giving the ESM output its own require keeps it loadable.
const esmRequirePrelude =
  'import { createRequire } from "node:module";\nconst require = createRequire(import.meta.url);\n';

const contractDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemasDir = join(contractDir, 'schemas');
const banner = '// Generated by contract/scripts/generate.ts. Do not edit.\n';

/** A schema file read from contract/schemas, keyed by its file stem. */
export interface LoadedSchema {
  /** File stem, for example `snapshot` for schemas/snapshot.schema.json. */
  name: string;
  schema: Record<string, unknown> & { $id: string; title?: string };
}

/** Reads every schemas/*.schema.json, sorted by file name. */
export async function loadSchemas(): Promise<LoadedSchema[]> {
  const files = (await readdir(schemasDir)).filter((file) => file.endsWith('.schema.json')).sort();
  return Promise.all(
    files.map(async (file) => ({
      name: file.slice(0, -'.schema.json'.length),
      schema: JSON.parse(await readFile(join(schemasDir, file), 'utf8')),
    })),
  );
}

/**
 * A $defs entry that fixes its `type` property to a constant, such as HelloFrame with "hello":
 * one member of a union that is told apart by `type`.
 */
function isUnionMember(definition: Record<string, unknown>): boolean {
  const properties = definition.properties as Record<string, Record<string, unknown>> | undefined;
  return properties?.type?.const !== undefined;
}

/** A tool schema definition: `ReadBookInput` and `ReadBookResult` are the pair for `read_book`. */
const TOOL_DEF = /^[A-Z][A-Za-z]*(Input|Result)$/;

type Defs = Record<string, Record<string, unknown>>;

/**
 * The validators to export, keyed by export name. Each schema with a title gets one named after
 * the title, and each union member in its $defs gets one named after the definition, pointing at
 * that definition by fragment so Ajv compiles it within the schema. Each tool input and result
 * definition (see TOOL_DEF) gets one too.
 */
function validatorExports(schemas: LoadedSchema[]): Map<string, string> {
  const exported = new Map<string, string>();
  const add = (exportName: string, target: string): void => {
    if (exported.has(exportName)) throw new Error(`duplicate validator export ${exportName}`);
    exported.set(exportName, target);
  };
  for (const { schema } of schemas) {
    const defs = (schema.$defs ?? {}) as Defs;
    if (schema.title !== undefined) {
      exported.set(`validate${schema.title}`, schema.$id);
      for (const [name, definition] of Object.entries(defs)) {
        if (isUnionMember(definition)) add(`validate${name}`, `${schema.$id}#/$defs/${name}`);
      }
    }
    for (const name of Object.keys(defs)) {
      if (TOOL_DEF.test(name)) add(`validate${name}`, `${schema.$id}#/$defs/${name}`);
    }
  }
  return exported;
}

/** One tool: the schema file holding its pair of definitions, and the names of both. */
interface ToolPair {
  tool: string;
  schemaName: string;
  inputName: string;
  resultName: string;
}

/** `ReadBook` becomes `read_book`. */
function snakeCase(pascal: string): string {
  return pascal.replace(/(?<=[a-z0-9])([A-Z])/g, '_$1').toLowerCase();
}

/** The tool pairs, sorted by tool name. Throws on an unpaired Input or Result, or an Input with no description. */
function toolPairs(schemas: LoadedSchema[]): ToolPair[] {
  const found = new Map<string, Partial<ToolPair>>();
  for (const { name: schemaName, schema } of schemas) {
    const defs = (schema.$defs ?? {}) as Defs;
    for (const [defName, definition] of Object.entries(defs)) {
      const match = TOOL_DEF.exec(defName);
      if (match === null) continue;
      const stem = defName.slice(0, -(match[1] as string).length);
      const entry = found.get(stem) ?? { tool: snakeCase(stem), schemaName };
      if (match[1] === 'Input') {
        if (typeof definition.description !== 'string' || definition.description === '') {
          throw new Error(`${defName} has no description`);
        }
        entry.inputName = defName;
      } else {
        entry.resultName = defName;
      }
      found.set(stem, entry);
    }
  }
  const pairs: ToolPair[] = [];
  for (const [stem, entry] of found) {
    if (entry.inputName === undefined) throw new Error(`${stem}Result has no ${stem}Input`);
    if (entry.resultName === undefined) throw new Error(`${stem}Input has no ${stem}Result`);
    pairs.push(entry as ToolPair);
  }
  return pairs.sort((a, b) => (a.tool < b.tool ? -1 : a.tool > b.tool ? 1 : 0));
}

/** Where a $ref points: the schema file, and the definition in it (undefined for the whole file). */
function resolveRef(ref: string, fromFile: string): { file: string; def: string | undefined } {
  const [path = '', fragment] = ref.split('#');
  const file = path === '' ? fromFile : path.replace(/\.schema\.json$/, '');
  if (fragment === undefined || fragment === '') return { file, def: undefined };
  const prefix = '/$defs/';
  if (!fragment.startsWith(prefix)) throw new Error(`unsupported $ref ${ref}`);
  return { file, def: fragment.slice(prefix.length) };
}

/**
 * A self-contained copy of one definition: `$defs` holds every definition it reaches, from any
 * schema file, and every `$ref` is rewritten to `#/$defs/<Name>` (a whole-file ref uses the file's
 * title). `$comment` is stripped everywhere; `$id`, `$schema` and `title` only at the root of each
 * definition, because properties may be called `title`. Throws on a missing target or when two
 * different definitions share a name.
 */
export function bundleDefinition(
  schemas: LoadedSchema[],
  schemaName: string,
  defName: string,
): Record<string, unknown> {
  const byName = new Map(schemas.map((s) => [s.name, s.schema]));
  const collected = new Map<string, { source: string; schema: unknown }>();

  const rewrite = (node: unknown, file: string): unknown => {
    if (Array.isArray(node)) return node.map((item) => rewrite(item, file));
    if (typeof node !== 'object' || node === null) return node;
    const out: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(node)) {
      if (key === '$comment') continue;
      out[key] =
        key === '$ref' && typeof value === 'string' ? reference(value, file) : rewrite(value, file);
    }
    return out;
  };

  const strip = (node: Record<string, unknown>): Record<string, unknown> => {
    const { $id, $schema, title, ...rest } = node;
    return rest;
  };

  const reference = (ref: string, fromFile: string): string => {
    const { file, def } = resolveRef(ref, fromFile);
    const schema = byName.get(file);
    if (schema === undefined) throw new Error(`$ref ${ref} names a missing schema file`);
    let name: string;
    let body: Record<string, unknown>;
    if (def === undefined) {
      if (schema.title === undefined) throw new Error(`$ref ${ref} targets an untitled schema`);
      name = schema.title;
      const { $defs: _ignored, ...whole } = schema;
      body = whole;
    } else {
      const found = ((schema.$defs ?? {}) as Defs)[def];
      if (found === undefined) throw new Error(`$ref ${ref} names a missing definition`);
      name = def;
      body = found;
    }
    const source = `${file}#${def ?? ''}`;
    const known = collected.get(name);
    if (known !== undefined) {
      if (known.source !== source) throw new Error(`two definitions are named ${name}`);
      return `#/$defs/${name}`;
    }
    collected.set(name, { source, schema: undefined });
    collected.set(name, { source, schema: rewrite(strip(body), file) });
    return `#/$defs/${name}`;
  };

  const root = ((byName.get(schemaName)?.$defs ?? {}) as Defs)[defName];
  if (root === undefined) throw new Error(`no definition ${defName} in ${schemaName}`);
  const body = rewrite(root, schemaName) as Record<string, unknown>;
  const defs = Object.fromEntries(
    [...collected.entries()]
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([name, { schema }]) => [name, schema]),
  );
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    ...body,
    ...(Object.keys(defs).length > 0 ? { $defs: defs } : {}),
  };
}

/** The generated mcp-tools.ts: tool names and a self-contained input and result schema per tool. */
function buildMcpTools(schemas: LoadedSchema[]): string {
  const pairs = toolPairs(schemas);
  const entries = pairs.map((pair) => {
    const defs = (schemas.find((s) => s.name === pair.schemaName)?.schema.$defs ?? {}) as Defs;
    const description = defs[pair.inputName]?.description;
    return [
      pair.tool,
      {
        description,
        input: bundleDefinition(schemas, pair.schemaName, pair.inputName),
        result: bundleDefinition(schemas, pair.schemaName, pair.resultName),
      },
    ];
  });
  const names = pairs.map((pair) => `'${pair.tool}'`).join(', ');
  return [
    banner,
    `export const MCP_TOOL_NAMES = [${names}] as const;\n`,
    'export type McpToolName = (typeof MCP_TOOL_NAMES)[number];\n',
    `export const mcpToolSchemas: Record<\n  McpToolName,\n  { description: string; input: Record<string, unknown>; result: Record<string, unknown> }\n> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`,
  ].join('\n');
}

/** Ajv's standalone validators, as ESM. Schemas are added before compiling so $refs stay local. */
async function buildValidators(schemas: LoadedSchema[]): Promise<string> {
  const ajv = new Ajv2020({ strict: true, allErrors: true, code: { source: true, esm: true } });
  addFormats(ajv);
  for (const { schema } of schemas) ajv.addSchema(schema);

  const exported = Object.fromEntries(validatorExports(schemas));
  return banner + esmRequirePrelude + standaloneCode(ajv, exported);
}

/** Declarations for validators.js, one per export of validatorExports. */
function buildValidatorDeclarations(schemas: LoadedSchema[]): string {
  const lines = [...validatorExports(schemas).keys()].map(
    (name) => `export declare const ${name}: ValidateFunction;`,
  );
  return `${banner}import type { ValidateFunction } from 'ajv';\n\n${lines.join('\n')}\n`;
}

/**
 * One exported type per titled schema, plus each definition of an untitled schema
 * (common.schema.json). json-schema-to-typescript also emits the definitions a schema
 * references from other files, so declarations are de-duplicated by name; the text of
 * a declaration is identical wherever it appears.
 */
async function buildTypes(schemas: LoadedSchema[]): Promise<string> {
  const declarations = new Map<string, string>();
  for (const { schema } of schemas) {
    const defNames = new Set(Object.keys(schema.$defs ?? {}));
    const text = await compile(schema as Parameters<typeof compile>[0], schema.title ?? 'Unnamed', {
      cwd: schemasDir,
      bannerComment: '',
      unreachableDefinitions: schema.title === undefined,
    });
    // Each declaration starts at column 0 (after its JSDoc, if any); nested members are indented.
    for (const part of text.split(/\n(?=(?:\/\*\*[\s\S]*?\*\/\n)?export )/)) {
      const match = /export (?:interface|type) (\w+)/.exec(part);
      const name = match?.[1];
      if (name === undefined || declarations.has(name)) continue;
      if (schema.title === undefined && !defNames.has(name)) continue;
      declarations.set(name, part.trim());
    }
  }
  return `${banner}\n${[...declarations.values()].join('\n\n')}\n`;
}

/** Every generated file, keyed by its path relative to contract/. */
export async function generate(): Promise<Map<string, string>> {
  const schemas = await loadSchemas();
  return new Map([
    ['src/generated/types.ts', await buildTypes(schemas)],
    ['src/generated/validators.js', await buildValidators(schemas)],
    ['src/generated/validators.d.ts', buildValidatorDeclarations(schemas)],
    ['src/generated/mcp-tools.ts', buildMcpTools(schemas)],
  ]);
}

/** Paths of generated files that are missing or differ from what the schemas produce. */
export async function findStale(): Promise<string[]> {
  const stale: string[] = [];
  for (const [path, text] of await generate()) {
    const current = await readFile(join(contractDir, path), 'utf8').catch(() => undefined);
    if (current !== text) stale.push(path);
  }
  return stale;
}
