// Generates src/legal-texts.generated.ts from docs/legal (LEGAL-SERVE). Run: node threshold/register/scripts/gen-legal.ts
// With a directory argument it prints the module to stdout instead of writing it. Exits non-zero on a missing or empty file.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The approved files: the key the module uses, and the file name in docs/legal. */
export const LEGAL_FILES = [
  { key: 'terms', file: 'terms.md' },
  { key: 'privacy', file: 'privacy.md' },
  { key: 'acceptable-use', file: 'acceptable-use.md' },
] as const;

const HERE = dirname(fileURLToPath(import.meta.url));
const DEFAULT_LEGAL_DIR = join(HERE, '..', '..', '..', 'docs', 'legal');
const OUT_FILE = join(HERE, '..', 'src', 'legal-texts.generated.ts');

/** Reads the three files. A missing or empty file throws, so no empty page is ever built. */
export function readSources(legalDir: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const { key, file } of LEGAL_FILES) {
    const text = readFileSync(join(legalDir, file), 'utf8');
    if (text.trim() === '') throw new Error(`${file} is empty`);
    out[key] = text;
  }
  return out;
}

const countOf = (text: string, ch: string): number => text.split(ch).length - 1;

/**
 * A TypeScript string literal for the exact text. It uses the quote with fewer escapes, as Biome does,
 * so the generated module is already formatted. Line and paragraph separators become escapes.
 */
function tsString(text: string): string {
  const quote = countOf(text, "'") > countOf(text, '"') ? '"' : "'";
  let body = '';
  for (const ch of text) {
    const code = ch.codePointAt(0) ?? 0;
    if (ch === '\\' || ch === quote) body += `\\${ch}`;
    else if (ch === '\n') body += '\\n';
    else if (ch === '\r') body += '\\r';
    else if (code === 0x2028 || code === 0x2029) body += `\\u${code.toString(16)}`;
    else body += ch;
  }
  return `${quote}${body}${quote}`;
}

const propName = (key: string): string => (/^[A-Za-z_]\w*$/.test(key) ? key : tsString(key));

/** The generated module text. The same bytes always give the same module. */
export function renderModule(legalDir: string): string {
  const sources = readSources(legalDir);
  // Long values go on the line after the key, as Biome formats them.
  const texts = LEGAL_FILES.map(
    ({ key }) => `  ${propName(key)}:\n    ${tsString(sources[key] ?? '')},`,
  );
  const hashes = LEGAL_FILES.map(({ key }) => {
    const digest = createHash('sha256')
      .update(sources[key] ?? '')
      .digest('hex');
    return `  ${propName(key)}: '${digest}',`;
  });
  return [
    '// Generated by threshold/register/scripts/gen-legal.ts from docs/legal. Do not edit by hand.',
    '',
    '/** The approved legal texts, byte for byte (LEGAL-SERVE, decisions 0153 and 0155). */',
    'export const LEGAL_TEXTS = {',
    ...texts,
    '} as const;',
    '',
    '/** SHA-256 of each file as read at build time. */',
    'export const LEGAL_SOURCE_SHA256 = {',
    ...hashes,
    '} as const;',
    '',
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dir = process.argv[2];
  const module = renderModule(dir ?? DEFAULT_LEGAL_DIR);
  if (dir) process.stdout.write(module);
  else writeFileSync(OUT_FILE, module);
}
