/**
 * The body helper runbook (docs/runbooks/body-helper-node-steps.md) must name the NATS subjects that the generator
 * (geldar.ps1) gives the `helper` and `supervisor` users, and the `helper.body.>` PubDeny of `body` and `paper`.
 * The runbook is text, so this test reads both files and compares the subject lists. It never runs the generator.
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const GENERATOR = readFileSync(`${ROOT}geldar.ps1`, 'utf8');
const RUNBOOK = readFileSync(`${ROOT}docs/runbooks/body-helper-node-steps.md`, 'utf8');
const VERBS = ['start', 'stop', 'status', 'logtail'];

/**
 * The generator text of one NATS user: from its `    user = @{` line to the next user (or the end of the list). A user
 * may span several lines (body and paper have their PubDeny on a later line), so the whole block is returned.
 */
function userLine(user: string): string {
  const lines = GENERATOR.split('\n');
  const start = lines.findIndex((text) => text.startsWith(`    ${user} = @{`));
  if (start < 0) throw new Error(`no generator line for NATS user ${user}`);
  let end = start + 1;
  while (
    end < lines.length &&
    !/^ {4}\w+ = @\{/.test(lines[end] as string) &&
    !/^ {2}\}/.test(lines[end] as string)
  ) {
    end += 1;
  }
  return lines.slice(start, end).join('\n');
}

/**
 * The subjects written in a generator line, with `$s` written as `<shard>` as the runbook writes it. The helper's four
 * verbs are generated by a loop (`"geldar.$s.helper.body.$_"`), so they are expanded here and the loop is checked.
 */
function subjectsIn(line: string): string[] {
  const found: string[] = [];
  for (const match of line.matchAll(/["'](geldar\.\$s\.[^"']+|_INBOX\.>)["']/g)) {
    const raw = match[1] as string;
    if (raw === 'geldar.$s.helper.body.$_') {
      expect(line, 'the verb loop must name the four verbs').toContain(
        "'start', 'stop', 'status', 'logtail'",
      );
      for (const verb of VERBS) found.push(`geldar.<shard>.helper.body.${verb}`);
    } else {
      found.push(raw.replace('geldar.$s.', 'geldar.<shard>.'));
    }
  }
  return found;
}

/** The generator's Pub or Sub subjects of one user (the `; `-separated piece of its line that holds the direction). */
function generatorSubjects(user: string, direction: 'Pub' | 'Sub'): string[] {
  const piece = userLine(user)
    .split('; ')
    .find((text) => text.includes(`${direction} = @(`));
  if (piece === undefined) throw new Error(`no ${direction} list for NATS user ${user}`);
  return subjectsIn(piece);
}

/** The runbook's section for one NATS user: from its `- **`user`**` bullet to the next user bullet. */
function runbookSection(user: string): string {
  const start = RUNBOOK.indexOf(`- **\`${user}\`**`);
  if (start < 0) throw new Error(`no runbook bullet for NATS user ${user}`);
  const next = RUNBOOK.indexOf('\n- **', start + 1);
  return RUNBOOK.slice(start, next < 0 ? undefined : next);
}

/** The subjects the runbook gives one direction (`Pub:` or `Sub:` sub-bullet) in a user's section. */
function runbookSubjects(section: string, direction: 'Pub' | 'Sub'): string[] {
  const found = section
    .split('\n  - ')
    .filter((bullet) => bullet.startsWith(`${direction}:`))
    .flatMap((bullet) =>
      [...bullet.matchAll(/geldar\.<shard>\.[\w.<>*-]+|_INBOX\.>/g)].map((m) => m[0]),
    );
  return [...new Set(found)].sort();
}

describe('body helper runbook against the generator', () => {
  it('reads the four helper verbs from the generator, so the comparison is not empty', () => {
    const helper = subjectsIn(userLine('helper'));
    expect(helper).toEqual([
      '_INBOX.>',
      'geldar.<shard>.helper.body.start',
      'geldar.<shard>.helper.body.stop',
      'geldar.<shard>.helper.body.status',
      'geldar.<shard>.helper.body.logtail',
    ]);
  });

  it('gives the helper exact subjects only: no wildcard in its subscribe list', () => {
    const subscribe = subjectsIn(userLine('helper')).filter((s) => s !== '_INBOX.>');
    expect(subscribe).toHaveLength(4);
    for (const subject of subscribe) expect(subject).not.toMatch(/[*>]$/);
  });

  it('names every helper and supervisor subject in the runbook text', () => {
    for (const user of ['helper', 'supervisor']) {
      for (const subject of subjectsIn(userLine(user))) {
        expect(RUNBOOK, `${user}: ${subject}`).toContain(subject);
      }
    }
  });

  it('names the supervisor control subject and the inbox the supervisor replies on', () => {
    expect(subjectsIn(userLine('supervisor'))).toContain('geldar.<shard>.ctl.body.>');
    expect(RUNBOOK).toContain('geldar.<shard>.ctl.body.>');
    expect(RUNBOOK).toContain('_INBOX.>');
  });

  it('has the helper.body.> PubDeny of body and paper in the generator and in the runbook', () => {
    for (const user of ['body', 'paper']) {
      expect(userLine(user), user).toContain('"geldar.$s.helper.body.>"');
    }
    expect(RUNBOOK).toContain('geldar.<shard>.helper.body.>');
  });

  it('gives each subject to the same user and direction (Pub or Sub) as the generator', () => {
    for (const user of ['helper', 'supervisor']) {
      const section = runbookSection(user);
      for (const direction of ['Pub', 'Sub'] as const) {
        const expected = [...new Set(generatorSubjects(user, direction))].sort();
        expect(runbookSubjects(section, direction), `${user} ${direction}`).toEqual(expected);
      }
    }
  });

  it('has no helper.body wildcard anywhere in the runbook', () => {
    expect(RUNBOOK).not.toMatch(/helper\.body\.\*/);
  });
});
